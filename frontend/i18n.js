  function t(key, vars) {
    const table = dict[lang] || dict.en;
    let s = (table && table[key]) || (dict.en && dict.en[key]) || key;
    if (vars && typeof vars === "object") {
      Object.keys(vars).forEach((k) => {
        s = s.replace(new RegExp("\\{" + k + "\\}", "g"), String(vars[k]));
      });
    }
    return s;
  }

  function getLang() {
    return lang;
  }

  function setLang(next) {
    if (next !== "es" && next !== "en") return;
    lang = next;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (_) {}
    applyStatic();
    if (typeof global.onLanguageChange === "function") {
      try {
        global.onLanguageChange(lang);
      } catch (e) {
        console.warn("onLanguageChange", e);
      }
    }
  }

  function applyStatic() {
    document.documentElement.setAttribute("lang", lang);
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (!key) return;
      const val = t(key);
      if (el.tagName === "INPUT" && el.hasAttribute("data-i18n-placeholder")) {
        el.placeholder = val;
      } else {
        el.textContent = val;
      }
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (key) el.placeholder = t(key);
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const key = el.getAttribute("data-i18n-title");
      if (key) el.title = t(key);
    });
    // language buttons active state
    document.querySelectorAll("[data-lang]").forEach((btn) => {
      btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
    });
  }

  function tutorialSteps() {
    // Built from dictionary keys so both languages stay in sync without a parallel TUTORIAL table.
    const mk = (prefix) => ({
      title: t(prefix + ".title"),
      body: t(prefix + ".body"),
    });
    // Prefer numbered tut.1..tut.7 if present, else fall back to generic steps.
    const steps = [];
    for (let i = 1; i <= 7; i++) {
      const titleKey = "tut." + i + ".title";
      const bodyKey = "tut." + i + ".body";
      const table = dict[lang] || dict.en;
      if (table && table[titleKey]) {
        steps.push({ title: t(titleKey), body: t(bodyKey) });
      }
    }
    if (steps.length) return steps;
    return [
      { title: t("tut.1.title") || t("btn.tutorial"), body: t("tut.1.body") || t("welcome.body") },
    ];
  }

  
